package com.recourse.data;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.recourse.engine.Attribute;
import com.recourse.engine.Career;
import org.springframework.core.io.ClassPathResource;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.InputStream;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;
import java.util.NoSuchElementException;

/** Loads the hand-curated careers.json. Career data is never generated by the language model. */
@Component
public class CareerCatalog {

    record JsonSource(String label, String url) {}
    record JsonCareer(String id, String title, String summary, String riasec, String onetCode,
                      Map<String, Map<String, Double>> weights, List<String> routes,
                      List<String> entranceExams, List<JsonSource> sources, boolean verified) {}

    private final List<Career> careers;

    @Autowired
    public CareerCatalog(ObjectMapper mapper) throws IOException {
        try (InputStream in = new ClassPathResource("careers.json").getInputStream()) {
            List<JsonCareer> raw = mapper.readValue(in, new TypeReference<>() {});
            this.careers = raw.stream().map(CareerCatalog::convert).toList();
        }
    }

    public CareerCatalog(List<Career> careers) {
        this.careers = List.copyOf(careers);
    }

    static Career convert(JsonCareer c) {
        Map<Attribute, Double> w = new EnumMap<>(Career.interestWeights(c.riasec()));
        if (c.weights() != null) {
            c.weights().values().forEach(group -> group.forEach((k, v) -> w.put(Attribute.fromKey(k), v)));
        }
        List<Career.Source> sources = c.sources() == null ? List.of()
                : c.sources().stream().map(s -> new Career.Source(s.label(), s.url())).toList();
        return new Career(c.id(), c.title(), c.summary(), c.riasec(), c.onetCode(), w,
                nullSafe(c.routes()), nullSafe(c.entranceExams()), sources, c.verified());
    }

    private static List<String> nullSafe(List<String> l) { return l == null ? List.of() : l; }

    public List<Career> all() { return careers; }

    public Career get(String id) {
        return careers.stream().filter(c -> c.id().equals(id)).findFirst()
                .orElseThrow(() -> new NoSuchElementException("Unknown career " + id));
    }
}
